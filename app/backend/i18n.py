def tr(key: str, lang: Lang = "RU") -> str:
    """Возвращает перевод строки по ключу. Если ключ не найден — возвращает сам ключ."""
    entry = TRANSLATIONS.get(key)
    if not entry:
        return key
    translation = entry.get(lang)
    if translation:
        return translation
    return entry.get("RU", key)


def get_available_languages() -> list[str]:
    """Возвращает список доступных языков."""
    return ["RU", "EN"]


def get_translation_keys() -> list[str]:
    """Возвращает все ключи переводов."""
    return list(TRANSLATIONS.keys())


def get_translation_coverage() -> dict[str, float]:
    """Возвращает процент покрытия переводов по каждому языку."""
    total = len(TRANSLATIONS)
    if total == 0:
        return {}
    coverage = {}
    for lang in get_available_languages():
        translated = sum(1 for entry in TRANSLATIONS.values() if entry.get(lang))
        coverage[lang] = translated / total
    return coverage
